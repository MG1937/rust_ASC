#[derive(Debug, PartialEq, Eq)]
struct OpcodeEntry {
    opcode: String,
    name: String,
    fmt: String,
    oplen: u32,
    idx: String,
    vflag: String,
}

fn parse_instruction_list(input: &str) -> Result<Vec<OpcodeEntry>, String> {
    let mut entries = Vec::new();

    for (line_number, line) in input.lines().enumerate() {
        let Some(start) = line.find("V(") else {
            continue;
        };
        let line = line[start + 2..].trim().trim_end_matches('\\').trim();
        let Some(line) = line.strip_suffix(')') else {
            continue;
        };
        let parts: Vec<&str> = line.split(',').map(str::trim).collect();
        if parts.len() != 8 || !parts[0].starts_with("0x") || !parts[2].starts_with('"') {
            continue;
        }

        let fmt = parts[3];
        let oplen = fmt
            .strip_prefix('k')
            .and_then(|value| value.chars().next())
            .and_then(|value| value.to_digit(10))
            .ok_or_else(|| format!("invalid opcode format on line {}", line_number + 1))?;
        let idx = parts[4];
        if idx == "kIndexUnknown" {
            continue;
        }
        let vflag = parts[7];
        if !vflag.starts_with("kVerify") {
            continue;
        }

        entries.push(OpcodeEntry {
            opcode: parts[0].to_string(),
            name: parts[2].trim_matches('"').to_string(),
            fmt: fmt.to_string(),
            oplen,
            idx: idx.to_string(),
            vflag: vflag.to_string(),
        });
    }

    if entries.is_empty() {
        return Err("no supported opcode macros found".to_string());
    }
    Ok(entries)
}

fn render_dvmopcode(entries: &[OpcodeEntry]) -> String {
    let mut OPCODE_FILL = String::new();
    for entry in entries {
        let vflag = entry.vflag.replace("kVerify", "VerifyFlag::kVerify");
        writeln!(
            OPCODE_FILL,
            "        m.insert({}, DvmOpcode::new(\"{}\", {}, Format::{}, IndexFlag::{}, {}));",
            entry.opcode,
            entry.name,
            entry.oplen,
            entry.fmt,
            entry.idx,
            vflag,
        )
        .expect("writing opcode template cannot fail");
    }
    DVM_OPCODE_TEMPLATE
        .replace("{opcodes}", &OPCODE_FILL)
        .trim_end_matches('\n')
        .to_string()
}

pub fn gen_dvmopcode(resource_dir: &Path, output_path: &Path) -> Result<(), String> {
    let instruction_list_path = resource_dir.join("dex_instruction_list.h");
    let instruction_list = fs::read_to_string(&instruction_list_path)
        .map_err(|e| format!("cannot read {}: {}", instruction_list_path.display(), e))?;
    let entries = parse_instruction_list(&instruction_list)?;
    let output = render_dvmopcode(&entries);
    fs::write(output_path, output)
        .map_err(|e| format!("cannot write {}: {}", output_path.display(), e))?;
    Ok(())
}

pub fn main() -> Result<(), String> {
    let resource_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/asc_core/resource");
    let output_path = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/asc_core/models/dvm_opcode.rs");
    gen_dvmopcode(&resource_dir, &output_path)?;
    println!("Gen Done");
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::Path;

    use super::{gen_dvmopcode, parse_instruction_list, render_dvmopcode};

    #[test]
    fn generates_current_opcode_table() {
        let entries = parse_instruction_list(include_str!("dex_instruction_list.h")).unwrap();
        assert_eq!(entries.len(), 224);
        assert_eq!(entries[0].opcode, "0x00");
        assert_eq!(entries[0].name, "nop");
        assert_eq!(entries.last().unwrap().opcode, "0xFF");

        let output = render_dvmopcode(&entries);
        let expected = include_str!("../models/dvm_opcode.rs");
        let mismatch = output
            .bytes()
            .zip(expected.bytes())
            .position(|(left, right)| left != right)
            .or_else(|| (output.len() != expected.len()).then_some(output.len().min(expected.len())));
        let mismatch_pos = mismatch.unwrap_or(0);
        let start = mismatch_pos.saturating_sub(24);
        let end = (mismatch_pos + 40).min(output.len());
        let expected_end = (mismatch_pos + 40).min(expected.len());
        assert_eq!(
            mismatch,
            None,
            "generated bytes={} expected bytes={} generated={:?} expected={:?}",
            output.len(),
            expected.len(),
            &output[start..end],
            &expected[start..expected_end],
        );
    }

    #[test]
    fn writes_current_opcode_table() {
        let resource_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/asc_core/resource");
        let output_path = std::env::temp_dir().join(format!(
            "rust_ASC_dvmopcode_{}.rs",
            std::process::id(),
        ));
        gen_dvmopcode(&resource_dir, &output_path).unwrap();
        let output = fs::read_to_string(&output_path).unwrap();
        let _ = fs::remove_file(&output_path);
        assert_eq!(output, include_str!("../models/dvm_opcode.rs"));
    }
}
